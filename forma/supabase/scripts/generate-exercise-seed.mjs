// Generates the exercise-library seed migration from the app's bundled
// library (app/assets/exercises.json), the single source of truth.
// Usage: node supabase/scripts/generate-exercise-seed.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = join(root, 'app', 'assets', 'exercises.json');
const target = join(root, 'supabase', 'migrations', '20261024000002_seed_exercises.sql');

const { version, exercises } = JSON.parse(readFileSync(source, 'utf8'));
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const rows = exercises.map((e) => `  (${[
  q(e.id), q(e.name), q(e.primary), q(e.secondary.join(',')), q(e.equipment.join(',')),
  q(e.pattern), q(e.mechanic), q(e.tracking), q(e.instructions.join('\n')),
].join(', ')})`);

const sql = `-- GENERATED by supabase/scripts/generate-exercise-seed.mjs from app/assets/exercises.json (version ${version}).
-- Do not edit by hand. Global library rows: user_id null, is_custom false.
insert into public.exercises (id, name, primary_muscle, secondary_muscles, equipment, pattern, mechanic, tracking_type, instructions)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  primary_muscle = excluded.primary_muscle,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  pattern = excluded.pattern,
  mechanic = excluded.mechanic,
  tracking_type = excluded.tracking_type,
  instructions = excluded.instructions,
  updated_at = now();
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== sql) {
    console.error('Exercise seed is out of date. Run: node supabase/scripts/generate-exercise-seed.mjs');
    process.exit(1);
  }
  console.log(`Exercise seed up to date (${exercises.length} exercises).`);
} else {
  writeFileSync(target, sql);
  console.log(`Wrote ${exercises.length} exercises to ${target}`);
}
