export const CARD_BY_ID: ReadonlyMap<string, CardDef> = new Map(CARDS.map((c) => [c.id, c]));

export function getCard(id: string): CardDef {
  const def = CARD_BY_ID.get(id);
  if (!def) throw new Error(`Unknown card ${id}`);
  return def;
}

